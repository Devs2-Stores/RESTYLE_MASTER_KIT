#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');
const { readValue, parseCsv } = require('./lib/cli-args');
const {
  findContract,
  readContract,
  scanResidue,
  scanZipResidue,
  deriveResidueVariants: deriveSingleVariant
} = require('./lib/remake-contract');
const { walkTheme } = require('./lib/theme-walk');
const { runSettingsSchemaAudit } = require('./lib/settings-audit');
function deriveResidueVariants(brands = []) {
  const brandList = Array.isArray(brands) ? brands : [brands];
  const variants = new Set();
  for (const b of brandList) {
    if (!b) continue;
    for (const v of deriveSingleVariant(b)) {
      variants.add(v);
    }
  }
  if (variants.size === 0) {
    return [
      'Stitch source:',
      'Generated by',
      'TODO',
      'FIXME',
      'hrv-hot-reload'
    ];
  }
  return Array.from(variants);
}
function parseArgs(argv) {
  const args = {
    root: path.resolve(process.cwd(), '..'),
    brands: [],
    sourceDomainWords: [],
    sourceDomainFile: '',
    zips: [],
    final: false,
    help: false
  };

  for (let i = 2; i < argv.length; i += 1) {
    const value = argv[i];
    if (value === '--help' || value === '-h') args.help = true;
    else if (value === '--root') { args.root = path.resolve(readValue(argv, i, '--root')); i += 1; }
    else if (value === '--brand' || value === '--brands') {
      const raw = readValue(argv, i, value);
      args.brands.push(...parseCsv(raw));
      i += 1;
    } else if (value === '--source-domain-words' || value === '--domain-words') {
      const raw = readValue(argv, i, value);
      args.sourceDomainWords.push(...parseCsv(raw));
      i += 1;
    } else if (value === '--source-domain-file' || value === '--domain-file') {
      args.sourceDomainFile = path.resolve(readValue(argv, i, value));
      i += 1;
    } else if (value === '--zip') { args.zips.push(path.resolve(readValue(argv, i, '--zip'))); i += 1; }
    else if (value === '--final') args.final = true;
    else throw new Error(`Unknown argument: ${value}`);
  }

  return args;
}

function loadSourceDomainWords(args, contract) {
  const words = new Set(args.sourceDomainWords || []);
  if (args.sourceDomainFile && fs.existsSync(args.sourceDomainFile)) {
    const raw = fs.readFileSync(args.sourceDomainFile, 'utf8').trim();
    if (raw.startsWith('[')) {
      try {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed)) parsed.forEach((w) => { if (w && String(w).trim()) words.add(String(w).trim()); });
      } catch (_) {}
    } else {
      for (const line of raw.split(/\r?\n/)) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        for (const w of parseCsv(trimmed)) words.add(w);
      }
    }
  }
  if (contract && Array.isArray(contract.sourceDomainWords)) {
    for (const w of contract.sourceDomainWords) {
      if (w && String(w).trim()) words.add(String(w).trim());
    }
  }
  return Array.from(words);
}

function escapeRegex(str) {
  return String(str).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function buildWordRegex(word) {
  const escaped = escapeRegex(word);
  const startsAscii = /^[a-z0-9]/i.test(word);
  const endsAscii = /[a-z0-9]$/i.test(word);
  return new RegExp(`${startsAscii ? '(?<![a-z0-9])' : ''}${escaped}${endsAscii ? '(?![a-z0-9])' : ''}`, 'i');
}

function scanDomainVocabulary(root, domainWords = []) {
  const findings = [];
  const words = Array.isArray(domainWords) ? domainWords : [];
  const wordRegexes = words.map((word) => ({ word, re: buildWordRegex(word) }));
  const seen = new Set();

  // 1. Scan config/settings_schema.json (label, info, default, content, placeholder)
  const schemaPath = path.join(root, 'config', 'settings_schema.json');
  if (fs.existsSync(schemaPath)) {
    try {
      const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
      if (Array.isArray(schema)) {
        for (const group of schema) {
          const gName = group.name || 'unnamed';
          for (const { word, re } of wordRegexes) {
            if (typeof group.name === 'string' && re.test(group.name)) {
              const key = `schema:group:${gName}:${word}`;
              if (!seen.has(key)) {
                seen.add(key);
                findings.push(`residue-vocabulary config/settings_schema.json:group[${gName}] matched "${word}"`);
              }
            }
          }
          for (const s of (group.settings || [])) {
            const id = s.id || s.type || 'header';
            for (const field of ['label', 'info', 'default', 'content', 'placeholder']) {
              const val = s[field];
              if (typeof val !== 'string' || !val) continue;
              for (const { word, re } of wordRegexes) {
                if (re.test(val)) {
                  const key = `schema:${id}:${field}:${word}`;
                  if (!seen.has(key)) {
                    seen.add(key);
                    findings.push(`residue-vocabulary config/settings_schema.json:${id}.${field} matched "${word}"`);
                  }
                }
              }
            }
          }
        }
      }
    } catch (_) {}
  }

  // 2. Scan config/settings_data.json (decoded unicode)
  const dataPath = path.join(root, 'config', 'settings_data.json');
  if (fs.existsSync(dataPath)) {
    try {
      const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));
      const current = (data && typeof data.current === 'object' && data.current) ? data.current : data;
      if (current && typeof current === 'object') {
        for (const [k, v] of Object.entries(current)) {
          if (typeof v !== 'string' || !v) continue;
          for (const { word, re } of wordRegexes) {
            if (re.test(v)) {
              const key = `data:${k}:${word}`;
              if (!seen.has(key)) {
                seen.add(key);
                findings.push(`residue-vocabulary config/settings_data.json:${k} matched "${word}"`);
              }
            }
          }
        }
      }
    } catch (_) {}
  }

  // 3. Scan window.themeConfig in layout/*.liquid and snippets/*.liquid
  const liquidFiles = walkTheme(root, { dirs: ['layout', 'snippets', 'templates'], ext: /\.liquid$/i });
  for (const file of liquidFiles) {
    const text = fs.readFileSync(file, 'utf8');
    if (!text.includes('themeConfig')) continue;
    const rel = path.relative(root, file).replace(/\\/g, '/');
    const lines = text.split(/\r?\n/);
    let inThemeConfig = false;
    let braceDepth = 0;
    for (let idx = 0; idx < lines.length; idx += 1) {
      const line = lines[idx];
      if (/window\.themeConfig\b/.test(line)) {
        inThemeConfig = true;
      }
      if (inThemeConfig) {
        for (const ch of line) {
          if (ch === '{') braceDepth += 1;
          else if (ch === '}') braceDepth -= 1;
        }
        for (const { word, re } of wordRegexes) {
          if (re.test(line)) {
            const key = `themeConfig:${rel}:${idx + 1}:${word}`;
            if (!seen.has(key)) {
              seen.add(key);
              findings.push(`residue-vocabulary ${rel}:${idx + 1} window.themeConfig matched "${word}"`);
            }
          }
        }
        if (braceDepth <= 0 && /;\s*$/.test(line)) {
          inThemeConfig = false;
          braceDepth = 0;
        }
      }
    }
  }

  // 4. Delegate to audit-settings-schema.mjs --residue-words if settings_schema.json exists (fail-closed)
  if (fs.existsSync(schemaPath) || process.env.HARAVAN_SETTINGS_AUDIT) {
    const auditRes = runSettingsSchemaAudit(root, {
      residueWords: domainWords,
      residueFile: undefined
    });
    for (const item of [...auditRes.errors, ...auditRes.warnings]) {
      if (item.rule === 'residue-vocabulary') {
        const idPart = item.key || item.id || '';
        const alreadyCovered = Array.from(seen).some((s) => idPart && s.includes(`:${idPart}:`));
        if (!alreadyCovered) {
          findings.push(`residue-vocabulary ${item.file || 'config/settings_schema.json'}${item.line ? ':' + item.line : (idPart ? ':' + idPart : '')} ${item.message}`);
        }
      }
    }
  }

  return findings;
}

function usage() {
  console.log(`Usage:
  node residue_scan.js --root <theme-root> [--brands "<brand1,brand2>"] [--brand "<old brand>"]... [--source-domain-words "<w1,w2>"] [--source-domain-file <file>] [--zip <file.zip>]... [--final]

Scans theme files, config/settings_schema.json, config/settings_data.json, window.themeConfig,
and optional ZIP archives for base-theme brand residue, donor-domain vocabulary, and generator markers.`);
}
function main() {
  const args = parseArgs(process.argv);
  if (args.help) {
    usage();
    return 0;
  }

  const markers = [];

  // 1. Pull markers from theme contract if available
  let contract = null;
  const contractPath = findContract(args.root);
  if (fs.existsSync(contractPath)) {
    try {
      contract = readContract(contractPath);
      if (Array.isArray(contract.residueMarkers)) {
        markers.push(...contract.residueMarkers);
      }
    } catch (_) {}
  }

  // 2. Add explicit --brand arguments
  for (const brand of args.brands) {
    markers.push({ value: brand, finalOnly: false });
  }

  // 3. Fallback defaults if no markers found
  if (!markers.length) {
    markers.push(
      { value: 'Stitch source:', finalOnly: false },
      { value: 'Generated by', finalOnly: false },
      { value: 'TODO', finalOnly: false },
      { value: 'FIXME', finalOnly: false },
      { value: 'hrv-hot-reload', finalOnly: true }
    );
  }

  const domainWords = loadSourceDomainWords(args, contract);
  const allFindings = [];

  // Scan theme directory
  if (fs.existsSync(args.root)) {
    const themeFindings = scanResidue(args.root, markers, args.final, contract?.allowlists?.residue || []);
    allFindings.push(...themeFindings);
    if (domainWords.length > 0 || fs.existsSync(path.join(args.root, 'config', 'settings_schema.json')) || process.env.HARAVAN_SETTINGS_AUDIT) {
      allFindings.push(...scanDomainVocabulary(args.root, domainWords));
    }
  }

  // Scan provided ZIP files
  for (const zipPath of args.zips) {
    const zipFindings = scanZipResidue(zipPath, markers, args.final);
    allFindings.push(...zipFindings);
  }

  console.log('# Residue Scan');
  console.log(`Root: ${args.root}`);
  if (args.brands.length) console.log(`Brands: ${args.brands.join(', ')}`);
  if (domainWords.length) console.log(`Source domain words: ${domainWords.join(', ')}`);
  if (args.zips.length) console.log(`ZIPs: ${args.zips.join(', ')}`);
  console.log(`Findings: ${allFindings.length}`);

  for (const finding of allFindings) {
    console.log(`- ${finding}`);
  }
  if (allFindings.length > 0) {
    return 1;
  }

  console.log('PASS: no base brand or generator residue detected.');
  return 0;
}

if (require.main === module) {
  try {
    process.exitCode = main() ?? 0;
  } catch (err) {
    console.error(`ERROR: ${err.message}`);
    process.exitCode = 1;
  }
}

module.exports = {
  parseArgs,
  deriveResidueVariants,
  scanResidue,
  scanZipResidue,
  scanDomainVocabulary,
  scanDomainWordsInRoot: scanDomainVocabulary,
  main
};
