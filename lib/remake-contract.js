const fs = require('fs');
const path = require('path');
const { walkTheme } = require('./theme-walk');

const CONTRACT_NAME = 'FULL_REMAKE_CONTRACT.json';
const PREVIEW_VERIFIED = new Set(['verified-preview', 'approved-final', 'waived', 'verified-static-hosted-auth']);
const FINAL_APPROVED = new Set(['approved-final', 'waived', 'verified-static-hosted-auth']);
const SYSTEM_RESIDUE_MARKERS = new Set(['stitch source:', 'generated by', 'todo', 'fixme', 'hrv-hot-reload']);
const RESIDUE_PREFIX_STOPWORDS = new Set(['hot', 'new', 'all', 'top', 'pro', 'dev', 'the', 'and', 'for', 'hrv', 'reload', 'stitch', 'source', 'generated']);
function findContract(root, explicitPath) {
  if (explicitPath) return path.resolve(explicitPath);
  const candidates = [
    path.join(root, 'deliverables', CONTRACT_NAME),
    path.join(root, CONTRACT_NAME)
  ];
  return candidates.find((file) => fs.existsSync(file)) || candidates[0];
}

function readContract(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function ledgerRequiresContract(text) {
  return /Layout mode:\s*(?:rebuild 100%|full remake)/i.test(text)
    || /full-remake contract/i.test(text);
}

function ledgerClaimsConvertedWithoutPreview(text) {
  const claimsConverted = /\|\s*converted\s*\|/i.test(text);
  const previewPending = /\|\s*Preview QA\s*\|\s*pending\s*\|/i.test(text);
  const evidencePending = /\|\s*Final evidence\s*\|\s*pending\s*\|/i.test(text);
  return claimsConverted && (previewPending || evidencePending);
}

function isAllowed(entry, file, line, content) {
  if (typeof entry === 'string') return entry === `${file}:${line}` || entry === file;
  if (!entry || typeof entry !== 'object') return false;
  if (entry.file && entry.file !== file) return false;
  if (entry.line && Number(entry.line) !== line) return false;
  if (entry.contains && !content.includes(entry.contains)) return false;
  if (entry.setting && !content.includes(`settings.${entry.setting}`) && !content.includes(`settings['${entry.setting}']`) && !content.includes(`settings["${entry.setting}"]`)) return false;
  return true;
}

function lineNumber(text, index) {
  return text.slice(0, index).split(/\r?\n/).length;
}
function escapeRegex(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function scanSettingsOnly(root, allowlist) {
  const findings = [];
  const files = walkTheme(root, { dirs: ['layout', 'snippets', 'templates'], ext: /\.liquid$/i });
  const patterns = [
    { rule: 'MERCHANT_DEFAULT', regex: /settings(?:\.[A-Za-z0-9_]+|\[[^\]]+\])\s*\|\s*default\s*:/g },
    { rule: 'FALLBACK_OBJECT_ALL', regex: /\b(?:blogs|collections)\.all\b/g }
  ];
  for (const filePath of files) {
    const relative = path.relative(root, filePath).replace(/\\/g, '/');
    const text = fs.readFileSync(filePath, 'utf8');
    for (const pattern of patterns) {
      const regex = new RegExp(pattern.regex.source, pattern.regex.flags);
      let match;
      while ((match = regex.exec(text)) !== null) {
        const line = lineNumber(text, match.index);
        if (allowlist.some((entry) => isAllowed(entry, relative, line, match[0]))) continue;
        findings.push(`${pattern.rule} ${relative}:${line} ${match[0]} (use '| plus: 0' and 'if settings.key != blank' instead of hard fallback text)`);
      }
    }
  }
  return findings;
}

function scanThemeImportant(root, allowlist, vendorFiles) {
  const findings = [];
  const files = walkTheme(root, { dirs: ['assets'], ext: /\.(?:css|scss(?:\.liquid|\.css)?)$/i });
  for (const filePath of files) {
    const relative = path.relative(root, filePath).replace(/\\/g, '/');
    if (vendorFiles.some((name) => relative.endsWith(name)) || /\.min\.css$/i.test(relative)) continue;
    const text = fs.readFileSync(filePath, 'utf8');
    const regex = /!important\b/g;
    let match;
    while ((match = regex.exec(text)) !== null) {
      const line = lineNumber(text, match.index);
      const sourceLine = text.split(/\r?\n/)[line - 1] || '';
      if (allowlist.some((entry) => isAllowed(entry, relative, line, sourceLine))) continue;
      findings.push(`THEME_IMPORTANT ${relative}:${line}`);
    }
  }
  return findings;
}

function scanCssOwnership(root, ownership) {
  const findings = [];
  const files = walkTheme(root, { dirs: ['assets'], ext: /\.(?:css|scss(?:\.liquid|\.css)?)$/i });
  const corpus = files.map((file) => fs.readFileSync(file, 'utf8')).join('\n');
  for (const item of ownership) {
    if (item.allowed === true || item.status === 'approved-deviation') continue;
    const legacy = (item.legacySelectors || []).filter((selector) => corpus.includes(selector));
    const target = (item.targetSelectors || []).filter((selector) => corpus.includes(selector));
    if (legacy.length && target.length) {
      findings.push(`DUAL_CSS_OWNER ${item.component || 'unnamed'} legacy=${legacy.join(',')} target=${target.join(',')}`);
    }
  }
  return findings;
}

const THRESHOLDS_FILE = path.join(__dirname, '..', 'registry', 'thresholds.json');

function loadThresholds(file = THRESHOLDS_FILE) {
  if (!fs.existsSync(file)) throw new Error(`thresholds file not found: ${file}`);
  const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const key of ['minTextPx']) {
    if (!Number.isFinite(parsed[key])) throw new Error(`thresholds file ${file} has no numeric ${key}`);
  }
  return parsed;
}

/**
 * designDefaults.typeScale is optional. When present it may only tighten the
 * registry text minimum (in px), never relax it.
 */
function validateTypeScale(dd, options = {}) {
  if (dd.typeScale === undefined) return [];
  const scale = dd.typeScale;
  if (!scale || typeof scale !== 'object' || Array.isArray(scale)) {
    return ['TYPE_SCALE_INVALID designDefaults.typeScale must be an object { minTextPx }'];
  }
  let thresholds;
  try {
    thresholds = options.thresholds || loadThresholds(options.thresholdsPath);
  } catch (error) {
    return [`TYPE_SCALE_THRESHOLDS_UNAVAILABLE ${error.message}`];
  }
  const findings = [];
  for (const key of ['minTextPx']) {
    const value = scale[key];
    if (!Number.isFinite(value) || value <= 0) {
      findings.push(`TYPE_SCALE_INVALID designDefaults.typeScale.${key}=${JSON.stringify(value)} (expected a positive number of px)`);
    } else if (value < thresholds[key]) {
      findings.push(`TYPE_SCALE_BELOW_MINIMUM designDefaults.typeScale.${key}=${value} minimum=${thresholds[key]}`);
    }
  }
  return findings;
}

function validateQaGate(contract) {
  const gate = contract.qaGate;
  if (gate === undefined) return [];
  if (!gate || typeof gate !== 'object' || Array.isArray(gate)) return ['QA_GATE_INVALID qaGate must be an object { widths, coverageFloor }'];
  const findings = [];
  if (!Array.isArray(gate.widths) || !gate.widths.length || !gate.widths.every((w) => Number.isInteger(w) && w > 0)) {
    findings.push('QA_GATE_INVALID qaGate.widths must be a non-empty array of positive integers');
  }
  if (!Number.isFinite(gate.coverageFloor) || gate.coverageFloor <= 0 || gate.coverageFloor > 1) {
    findings.push(`QA_GATE_INVALID qaGate.coverageFloor=${JSON.stringify(gate.coverageFloor)} (expected a number in (0, 1])`);
  }
  return findings;
}

const HOME_STRUCTURE_FILE = path.join(__dirname, '..', 'registry', 'home-structure.json');
const DESIGN_TOKEN_KEYS = ['spacingScale', 'radius', 'controlHeight', 'iconStroke', 'cardDensity', 'homeSectionBudget'];
const CARD_DENSITIES = new Set(['compact', 'comfortable', 'spacious']);
const MIN_REFERENCE_CAPTURES = 2;

function loadHomeStructure(file = HOME_STRUCTURE_FILE) {
  if (!fs.existsSync(file)) throw new Error(`home structure file not found: ${file}`);
  const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  const budget = parsed && parsed.budget;
  if (!budget || !Number.isInteger(budget.min) || !Number.isInteger(budget.max) || budget.min < 1 || budget.min > budget.max) {
    throw new Error(`home structure file ${file} has no valid budget { min, max }`);
  }
  return parsed;
}

function isPlainObject(value) {
  return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
}

/** The contract budget may only narrow the registry budget. */
function effectiveHomeBudget(dd, structure, findings) {
  const registry = structure.budget;
  const declared = dd.homeSectionBudget;
  if (declared === undefined) return { min: registry.min, max: registry.max };
  const valid = isPlainObject(declared) && Number.isInteger(declared.min) && Number.isInteger(declared.max) && declared.min <= declared.max;
  if (!valid) {
    findings.push(`DESIGN_TOKEN_INVALID designDefaults.homeSectionBudget=${JSON.stringify(declared)} (expected { min, max } integers)`);
    return { min: registry.min, max: registry.max };
  }
  if (declared.min < registry.min || declared.max > registry.max) {
    findings.push(`DESIGN_TOKEN_INVALID designDefaults.homeSectionBudget=${declared.min}-${declared.max} is outside the registry budget ${registry.min}-${registry.max}`);
    return { min: registry.min, max: registry.max };
  }
  return { min: declared.min, max: declared.max };
}

function validateHomeBudget(dd, designGate, options = {}) {
  const findings = [];
  let structure;
  try {
    structure = options.homeStructure || loadHomeStructure(options.homeStructurePath);
  } catch (error) {
    return [`HOME_STRUCTURE_UNAVAILABLE ${error.message}`];
  }
  const budget = effectiveHomeBudget(dd, structure, findings);
  if (Array.isArray(dd.homeSectionOrder)) {
    const excluded = new Set((Array.isArray(structure.countExcludes) ? structure.countExcludes : []).map(foldText));
    const count = dd.homeSectionOrder.filter((entry) => !excluded.has(foldText(entryName(entry)))).length;
    if (count > budget.max || (designGate && count < budget.min)) {
      findings.push(`HOME_SECTION_BUDGET designDefaults.homeSectionOrder lists ${count} section(s), budget is ${budget.min}-${budget.max}`);
    }
  }
  return findings;
}

/** Token shapes the Phase 0 design gate locks; a present key is always checked, a missing one only under the gate. */
function validateDesignTokens(dd, designGate, options = {}) {
  const findings = [];
  const present = (key) => dd[key] !== undefined;
  if (designGate) {
    for (const key of ['typeScale', ...DESIGN_TOKEN_KEYS]) {
      if (!present(key)) findings.push(`DESIGN_TOKEN_MISSING designDefaults.${key}`);
    }
  }
  const invalid = (key, why) => findings.push(`DESIGN_TOKEN_INVALID designDefaults.${key}=${JSON.stringify(dd[key])} (${why})`);
  if (present('spacingScale')) {
    const scale = dd.spacingScale;
    const numeric = Array.isArray(scale) && scale.every((n) => Number.isFinite(n) && n > 0);
    if (!numeric || scale.length < 4) invalid('spacingScale', 'expected at least 4 positive px numbers');
    else if (scale.some((n, i) => i > 0 && n <= scale[i - 1])) invalid('spacingScale', 'expected a strictly ascending scale');
  }
  if (present('radius')) {
    const radius = dd.radius;
    const entries = isPlainObject(radius) ? Object.values(radius) : [];
    if (!entries.length || !entries.every((v) => (Number.isFinite(v) && v >= 0) || (typeof v === 'string' && v.trim()))) {
      invalid('radius', 'expected an object of named radii, each a non-negative number or a CSS length string');
    }
  }
  if (present('controlHeight')) {
    const height = dd.controlHeight;
    const touch = isPlainObject(height) ? height.mobile : height;
    if (!Number.isFinite(touch) || touch <= 0) {
      invalid('controlHeight', 'expected a positive px number or { mobile, desktop } with a numeric mobile');
    }
  }
  if (present('iconStroke') && !(Number.isFinite(dd.iconStroke) && dd.iconStroke > 0 && dd.iconStroke <= 4)) {
    invalid('iconStroke', 'expected a number in (0, 4]');
  }
  if (present('cardDensity') && !CARD_DENSITIES.has(dd.cardDensity)) {
    invalid('cardDensity', `expected one of ${[...CARD_DENSITIES].join(', ')}`);
  }
  return findings;
}

/** Phase 0 evidence: at least MIN_REFERENCE_CAPTURES parseable reference captures under deliverables/reference. */
function validateDesignReferences(root) {
  const dir = path.join(root, 'deliverables', 'reference');
  const files = fs.existsSync(dir) && fs.statSync(dir).isDirectory()
    ? fs.readdirSync(dir).filter((name) => /\.json$/i.test(name))
    : [];
  const findings = [];
  if (files.length < MIN_REFERENCE_CAPTURES) {
    findings.push(`DESIGN_GATE_MISSING deliverables/reference/*.json has ${files.length} capture(s), need at least ${MIN_REFERENCE_CAPTURES} (anti.reference.capture or page_inventory of the chosen references)`);
  }
  for (const name of files) {
    try {
      JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
    } catch (error) {
      findings.push(`DESIGN_GATE_REFERENCE_INVALID deliverables/reference/${name}: ${error.message}`);
    }
  }
  return findings;
}

function foldText(value) {
  return String(value || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/đ/gi, 'd').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

function readHomeCapture(file) {
  const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  const candidates = [parsed, parsed && parsed.inventory, parsed && parsed.result, parsed && parsed.data];
  const found = candidates.find((value) => value && Array.isArray(value.sections));
  if (!found) throw new Error(`${file} has no sections[] (expected an anti.inspect.page_inventory result)`);
  return found;
}

function entryName(entry) {
  if (typeof entry === 'string') return entry;
  return entry && typeof entry === 'object' ? String(entry.name || entry.role || entry.id || '') : '';
}

/** Greedy in-order match of each declared home section against the live page inventory. */
function compareHomeCapture(order, capture, structure) {
  const findings = [];
  const live = capture.sections
    .filter((section) => section && section.group !== 'header-group' && section.tag !== 'header')
    .map((section) => ({ section, hay: foldText([section.id, section.selector, section.heading].filter(Boolean).join(' ')), y: Number(section.y) || 0 }))
    .sort((a, b) => a.y - b.y);
  const matches = (item, name) => {
    const folded = foldText(name);
    const keywords = structure.roleKeywords && structure.roleKeywords[folded];
    const needles = [folded, ...(Array.isArray(keywords) ? keywords.map(foldText) : [])].filter(Boolean);
    return needles.some((needle) => item.hay.includes(needle));
  };
  let previous = -1;
  let previousName = null;
  for (const entry of order) {
    const name = entryName(entry);
    if (!name) continue;
    let hit = -1;
    for (let i = previous + 1; i < live.length; i += 1) {
      if (matches(live[i], name)) { hit = i; break; }
    }
    if (hit >= 0) {
      previous = hit;
      previousName = name;
      continue;
    }
    const earlier = live.findIndex((item) => matches(item, name));
    if (earlier >= 0 && previousName) {
      findings.push(`HOME_ORDER_MISMATCH "${name}" renders at position ${earlier + 1}, before "${previousName}" (contract order puts it after)`);
    } else {
      findings.push(`HOME_ORDER_MISMATCH "${name}" not found among the ${live.length} live home section(s)`);
    }
  }
  return findings;
}

function validateScreens(contract, finalMode, root) {
  const findings = [];
  const screens = Array.isArray(contract.screens) ? contract.screens : [];
  if (!screens.length) findings.push('SCREENS_EMPTY no approved screen inventory');
  for (const screen of screens) {
    const label = screen.name || 'unnamed';
    const isAccountScreen = /^account/i.test(label) || /^customers\b/i.test(label);
    const isHostedAuth = screen.status === 'verified-static-hosted-auth';
    if (isHostedAuth && !isAccountScreen && !screen.hostedAuthRedirect) {
      findings.push(`INVALID_HOSTED_AUTH_STATUS ${label} (verified-static-hosted-auth is only valid for account-* screens with hostedAuthRedirect)`);
    }
    if (isHostedAuth && root) {
      const customersDir = path.join(root, 'templates', 'customers');
      const flatAccounts = walkTheme(root, { dirs: ['templates'], ext: /\.liquid$/i }).filter((f) => /customers/i.test(path.basename(f)));
      const hasCustomers = (fs.existsSync(customersDir) && fs.readdirSync(customersDir).some((f) => f.endsWith('.liquid'))) || flatAccounts.length > 0;
      if (!hasCustomers) {
        findings.push(`HOSTED_AUTH_MISSING_STATIC_TEMPLATES ${label}`);
      }
    }
    if (screen.path !== undefined && (typeof screen.path !== 'string' || !/^\/(?!\/)[^\s#]*$/.test(screen.path))) {
      findings.push(`SCREEN_PATH_INVALID ${label} path=${JSON.stringify(screen.path)} (expected a storefront path starting with a single "/")`);
    }
    if (!Array.isArray(screen.landmarks) || !screen.landmarks.length) findings.push(`LANDMARKS_EMPTY ${label}`);
    if (PREVIEW_VERIFIED.has(screen.status)) {
      if (!isHostedAuth && (!screen.evidence?.desktop || !screen.evidence?.mobile)) {
        findings.push(`CONVERTED_WITHOUT_VISUAL_EVIDENCE ${label}`);
      }
      const incomplete = (screen.landmarks || []).filter((item) => !['matched', 'approved-deviation'].includes(item.status));
      if (incomplete.length) findings.push(`LANDMARKS_PENDING ${label} count=${incomplete.length}`);
    }
    if (finalMode && !FINAL_APPROVED.has(screen.status)) findings.push(`SCREEN_NOT_APPROVED_FINAL ${label} status=${screen.status || 'missing'}`);
  }
  return findings;
}

function validateFeatures(root, contract, finalMode) {
  const findings = [];
  const features = Array.isArray(contract.features) ? contract.features : [];
  if (!features.length) findings.push('FEATURES_EMPTY no pre-change feature inventory');
  for (const feature of features) {
    const label = feature.name || 'unnamed';
    if (!Array.isArray(feature.sourceHooks) || !feature.sourceHooks.length) findings.push(`FEATURE_SOURCE_HOOKS_EMPTY ${label}`);
    if (!Array.isArray(feature.targetHooks) || !feature.targetHooks.length) findings.push(`FEATURE_TARGET_HOOKS_EMPTY ${label}`);
    for (const hook of feature.targetHooks || []) {
      const spec = typeof hook === 'string' && hook.includes('::')
        ? { file: hook.slice(0, hook.indexOf('::')), contains: hook.slice(hook.indexOf('::') + 2) }
        : hook;
      if (!spec || typeof spec !== 'object' || !spec.file || !spec.contains) {
        findings.push(`FEATURE_TARGET_HOOK_UNVERIFIABLE ${label}`);
        continue;
      }
      const filePath = path.join(root, spec.file);
      if (!fs.existsSync(filePath) || !fs.readFileSync(filePath, 'utf8').includes(spec.contains)) {
        findings.push(`FEATURE_HOOK_MISSING ${label} ${spec.file}::${spec.contains}`);
      }
    }
    if (feature.status === 'preserved' && (!Array.isArray(feature.evidence) || !feature.evidence.length)) findings.push(`FEATURE_WITHOUT_EVIDENCE ${label}`);
    if (finalMode && !['preserved', 'approved-deviation'].includes(feature.status)) findings.push(`FEATURE_NOT_PRESERVED ${label} status=${feature.status || 'missing'}`);
  }
  return findings;
}

function validateSharedPrimitives(contract) {
  const findings = [];
  for (const primitive of contract.sharedPrimitives || []) {
    if (Number(primitive.occurrences || 0) >= 2 && !primitive.canonical && !primitive.deviation) {
      findings.push(`SHARED_PRIMITIVE_DRIFT ${primitive.name || 'unnamed'}`);
    }
  }
  return findings;
}

function deriveResidueVariants(marker, options = {}) {
  const spec = (marker && typeof marker === 'object') ? marker : { value: marker };
  const raw = String(spec.value ?? marker ?? '').trim();
  if (!raw) return [];
  const variants = new Set();
  const lower = raw.toLowerCase();
  variants.add(lower);

  const isSystem = SYSTEM_RESIDUE_MARKERS.has(lower) || spec.derivePrefixes === false || options.derivePrefixes === false;
  if (isSystem) {
    return Array.from(variants);
  }

  const words = lower.split(/[\s\-_.]+/).filter(Boolean);
  if (words.length > 1) {
    variants.add(words.join(''));       // e.g. "s2spa"
    variants.add(words.join('-'));      // e.g. "s2-spa"
    variants.add(words.join('_'));      // e.g. "s2_spa"
    variants.add(words.join(' '));      // e.g. "s2 spa"
  } else if (words.length === 1 && words[0].length > 2) {
    variants.add(words[0]);
  }

  // Derive key and class prefixes for brand component words (excluding generic stopwords)
  for (const word of words) {
    if (word.length >= 3 && !RESIDUE_PREFIX_STOPWORDS.has(word)) {
      variants.add(`${word}_`);
      variants.add(`${word}-`);
    }
  }

  return Array.from(variants);
}

function buildVariantRegex(variant) {
  const escaped = escapeRegex(variant);
  const startsAlnum = /^[a-z0-9]/i.test(variant);
  const endsAlnum = /[a-z0-9]$/i.test(variant);
  const prefix = startsAlnum ? '(?<![a-z0-9])' : '';
  const suffix = endsAlnum ? '(?![a-z0-9])' : '';
  return new RegExp(`${prefix}${escaped}${suffix}`, 'gi');
}

function decodeJsonUnicodeEscapes(text) {
  return String(text || '').replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) => String.fromCharCode(parseInt(hex, 16)));
}

function scanResidueInText(text, filePathLabel, markers, finalMode, allowlist = []) {
  const findings = [];
  const seenMatches = new Set();
  const scanText = /\.json$/i.test(filePathLabel) ? decodeJsonUnicodeEscapes(text) : text;
  const lines = scanText.split(/\r?\n/);
  for (const marker of markers) {
    const spec = typeof marker === 'string' ? { value: marker, finalOnly: false } : marker;
    if (!spec?.value || (spec.finalOnly && !finalMode)) continue;
    const variants = deriveResidueVariants(spec);
    for (const variant of variants) {
      if (!variant) continue;
      const regex = buildVariantRegex(variant);
      let match;
      while ((match = regex.exec(scanText)) !== null) {
        const line = lineNumber(scanText, match.index);
        const sourceLine = lines[line - 1] || '';
        if (Array.isArray(allowlist) && allowlist.some((entry) => isAllowed(entry, filePathLabel, line, sourceLine))) continue;
        const matchKey = `${filePathLabel}:${line}:${match.index}`;
        if (seenMatches.has(matchKey)) continue;
        seenMatches.add(matchKey);
        findings.push(`GENERATOR_RESIDUE ${filePathLabel}:${line} ${match[0]}`);
      }
    }
  }
  return findings;
}

function scanResidue(root, markers, finalMode, allowlist = []) {
  const findings = [];
  const files = walkTheme(root, { dirs: ['assets', 'config', 'layout', 'snippets', 'templates'], ext: /\.(?:css|js|json|liquid|html)$/i });
  const settingsData = path.join(root, 'config', 'settings_data.json');
  if (fs.existsSync(settingsData) && !files.includes(settingsData)) {
    files.push(settingsData);
  }
  for (const filePath of files) {
    if (/\.(?:min\.css|min\.js)$/i.test(filePath)) continue;
    const text = fs.readFileSync(filePath, 'utf8');
    const relative = path.relative(root, filePath).replace(/\\/g, '/');
    findings.push(...scanResidueInText(text, relative, markers, finalMode, allowlist));
  }
  return findings;
}

function scanZipResidue(zipPath, markers, finalMode) {
  const { readZipEntriesWithData } = require('./zip');
  const findings = [];
  if (!fs.existsSync(zipPath)) return findings;
  let entries;
  try {
    entries = readZipEntriesWithData(zipPath);
  } catch (err) {
    findings.push(`GENERATOR_RESIDUE [ZIP_ERROR] ${path.basename(zipPath)}: ${err.message}`);
    return findings;
  }
  for (const entry of entries) {
    if (/\.(?:min\.css|min\.js)$/i.test(entry.name)) continue;
    if (!/\.(?:css|js|json|liquid|html|txt|xml)$/i.test(entry.name)) continue;
    const text = entry.text || '';
    if (!text) continue;
    const label = `[ZIP] ${path.basename(zipPath)}::${entry.name}`;
    findings.push(...scanResidueInText(text, label, markers, finalMode));
  }
  return findings;
}

function validateDesignDefaults(root, contract, options = {}) {
  const findings = [];
  const dd = contract.designDefaults;
  if (!dd || typeof dd !== 'object') {
    findings.push('DESIGN_DEFAULTS_MISSING missing designDefaults block in FULL_REMAKE_CONTRACT.json');
    return findings;
  }
  const requiredFields = ['canvasColor', 'mobileRootFontPx', 'priceColor', 'sectionSpace', 'gutterToken', 'homeSectionOrder'];
  for (const field of requiredFields) {
    if (!(field in dd) || dd[field] === undefined || dd[field] === null || dd[field] === '') {
      findings.push(`DESIGN_DEFAULTS_FIELD_MISSING designDefaults.${field}`);
    }
  }
  if (typeof dd.mobileRootFontPx !== 'number' || dd.mobileRootFontPx <= 0) {
    findings.push(`DESIGN_DEFAULTS_INVALID mobileRootFontPx=${dd.mobileRootFontPx}`);
  }
  findings.push(...validateTypeScale(dd, options));
  if (!Array.isArray(dd.homeSectionOrder)) {
    findings.push('DESIGN_DEFAULTS_INVALID designDefaults.homeSectionOrder must be an array');
  }
  // A contract that carries any gate token opts into the full Phase 0 design gate.
  const designGate = options.designGate === true || DESIGN_TOKEN_KEYS.some((key) => dd[key] !== undefined);
  findings.push(...validateDesignTokens(dd, designGate, options));
  findings.push(...validateHomeBudget(dd, designGate, options));
  if (designGate) findings.push(...validateDesignReferences(root));
  if (options.homeCapturePath && Array.isArray(dd.homeSectionOrder)) {
    try {
      const structure = options.homeStructure || loadHomeStructure(options.homeStructurePath);
      findings.push(...compareHomeCapture(dd.homeSectionOrder, readHomeCapture(options.homeCapturePath), structure));
    } catch (error) {
      findings.push(`HOME_CAPTURE_UNREADABLE ${error.message}`);
    }
  }
  const cssFiles = walkTheme(root, { dirs: ['assets', 'snippets', 'layout'], ext: /\.(?:css|liquid)$/i });
  const corpus = cssFiles.map((f) => fs.readFileSync(f, 'utf8')).join('\n');
  if (!/--[a-z0-9-]*color-price\s*:/i.test(corpus)) {
    findings.push('DESIGN_DEFAULTS_PRICE_TOKEN_MISSING missing --<pfx>-color-price token in theme CSS');
  }
  const hasMobileRootFont = /@media[^{]*(?:max-width\s*:\s*76[78]px|width\s*<=\s*76[78]px)[\s\S]{0,600}?(?:html|:root)\s*\{[^}]*font-size\s*:/i.test(corpus)
    || /(?:html|:root)\s*\{[^}]*font-size\s*:\s*14px/i.test(corpus);
  if (!hasMobileRootFont) {
    findings.push(`DESIGN_DEFAULTS_MOBILE_ROOT_FONT_MISSING missing mobile root font-size rule (${dd.mobileRootFontPx}px at <=767px) in theme CSS`);
  }
  return findings;
}

function validateRemakeContract(root, contract, options = {}) {
  const finalMode = Boolean(options.final);
  const findings = [];
  if (contract.version !== 1) findings.push(`CONTRACT_VERSION expected=1 actual=${contract.version}`);
  const dataPolicy = contract.policy?.merchantData || 'legacy-default';
  findings.push(...validateDesignDefaults(root, contract, options));
  findings.push(...validateQaGate(contract));
  findings.push(...validateScreens(contract, finalMode, root));
  findings.push(...validateFeatures(root, contract, finalMode));
  findings.push(...validateSharedPrimitives(contract));
  findings.push(...scanCssOwnership(root, contract.cssOwnership || []));
  findings.push(...scanResidue(root, contract.residueMarkers || [], finalMode, contract.allowlists?.residue || []));
  if (dataPolicy === 'settings-only') findings.push(...scanSettingsOnly(root, contract.allowlists?.merchantDefaults || []));
  findings.push(...scanThemeImportant(root, contract.allowlists?.themeImportant || [], contract.allowlists?.vendorCss || ['swiper.css', 'aos.css']));
  if (finalMode && contract.preview?.status !== 'passed') findings.push(`PREVIEW_NOT_PASSED status=${contract.preview?.status || 'missing'}`);
  return findings;
}

